/**
 * Пересчёт суммы по курсу — ОДНО место на весь проект.
 *
 * Курс в Ecash всегда котируется к тенге: «541,68 ₸ = 1 $». Поэтому
 * направление считается не «умножить или разделить по вкусу», а строго по
 * тому, что клиент ОТДАЁТ:
 *   отдаёт тенге (currencyFrom === 'KZT') → получает валюту → value / rate;
 *   отдаёт валюту                          → получает тенге  → value * rate.
 *
 * Логика вынесена сюда после реального бага: при ответе казначея по
 * индивидуальному курсу сумма пересчитывалась `value * rate` БЕЗУСЛОВНО, и
 * заявка «1 000 000 ₸ → $» показывала 541 680 000 $ вместо 1 846 $. Формула
 * была продублирована в трёх местах, и разошлась ровно там, где её забыли
 * поправить, — поэтому теперь она существует в единственном экземпляре и
 * покрыта тестами.
 */

/** Клиент отдаёт тенге (обменник продаёт валюту). */
export function isKztGive(currencyFrom: string): boolean {
  return currencyFrom === 'KZT';
}

/**
 * Сумма встречной стороны: сколько клиент ПОЛУЧИТ, отдав `value`.
 * Некорректный курс (0, отрицательный, NaN) даёт 0 — вызывающий код
 * показывает пустое поле, а не «Infinity» и не «NaN».
 */
export function counterAmount(value: number, rate: number, currencyFrom: string): number {
  if (!Number.isFinite(value) || !Number.isFinite(rate) || rate <= 0) return 0;
  return isKztGive(currencyFrom) ? value / rate : value * rate;
}

/** Во сколько раз целевой курс подписки может отличаться от текущего. */
const RATE_TOLERANCE = 10;

/**
 * Правдоподобен ли целевой курс подписки на уведомление.
 *
 * В поле «Уведомить при курсе (₸)» вводят КУРС ЗА ЕДИНИЦУ, а не сумму обмена,
 * но проверки на это не было: подходило любое положительное число, и в
 * подписке оседали значения вроде 60 000 000 ₸ за доллар — такой курс не
 * наступит никогда, уведомление молча не сработает.
 *
 * Допуск нарочно широкий (÷10 … ×10): ждать сильного движения курса не мешаем,
 * а промах на порядок и ввод суммы вместо курса ловим. Пока курс отделения не
 * загружен (current <= 0), не придираемся — иначе форма блокировалась бы из-за
 * недоступности апстрима.
 */
export function isPlausibleTargetRate(target: number, current: number): boolean {
  if (!Number.isFinite(target) || target <= 0) return false;
  if (!Number.isFinite(current) || current <= 0) return true;
  return target >= current / RATE_TOLERANCE && target <= current * RATE_TOLERANCE;
}

/**
 * Суммы сделки: сколько валюты и сколько тенге реально уйдёт в заявку.
 *
 * Обменник оперирует целыми единицами валюты и целыми тенге — так же
 * считает и ядро Ecash (раздел 4.1 «Суммы» его документации: «Остатка не
 * остаётся: валюта — целыми единицами… Бэкенд срезает дробный хвост и
 * пересчитывает тенге по целой валюте… Тенге тоже уходят целым числом»).
 * Ядро прямо рекомендует фронту делать этот расчёт заранее и показывать
 * его человеку, чтобы экран не расходился с заявкой.
 *
 * Функция общая для формы и для серверной отправки — оба места обязаны
 * получать одни и те же числа, иначе клиент увидит одно, а забронирует
 * другое.
 *
 * @param value  сумма, которую ввёл клиент (что он ОТДАЁТ)
 * @param rate   тенге за единицу валюты
 * @param kztGive клиент отдаёт тенге (пара KZT → валюта)
 */
export function dealAmounts(
  value: number,
  rate: number,
  kztGive: boolean,
): { foreign: number; tenge: number } {
  if (!Number.isFinite(value) || !Number.isFinite(rate) || rate <= 0 || value <= 0) {
    return { foreign: 0, tenge: 0 };
  }
  // +1e-9 гасит двоичную пыль плавающей точки: 64.8 / 0.72 = 89.999… ≠ 90
  const foreign = Math.floor((kztGive ? value / rate : value) + 1e-9);
  return { foreign, tenge: Math.round(foreign * rate) };
}
