/**
 * Пересчёт суммы по курсу — ОДНО место на весь проект.
 *
 * Курс в Ecash всегда котируется к тенге: «541,68 ₸ = 1 $». Поэтому
 * направление считается не «умножить или разделить по вкусу», а строго по
 * тому, что клиент ОТДАЁТ:
 *   отдаёт тенге (currencyFrom === 'KZT') → получает валюту → value / rate;
 *   отдаёт валюту                          → получает тенге  → value * rate.
 *
 * Логика вынесена сюда после реального бага: при ответе казначея по
 * индивидуальному курсу сумма пересчитывалась `value * rate` БЕЗУСЛОВНО, и
 * заявка «1 000 000 ₸ → $» показывала 541 680 000 $ вместо 1 846 $. Формула
 * была продублирована в трёх местах, и разошлась ровно там, где её забыли
 * поправить, — поэтому теперь она существует в единственном экземпляре и
 * покрыта тестами.
 */

/** Клиент отдаёт тенге (обменник продаёт валюту). */
export function isKztGive(currencyFrom: string): boolean {
  return currencyFrom === 'KZT';
}

/**
 * Сумма встречной стороны: сколько клиент ПОЛУЧИТ, отдав `value`.
 * Некорректный курс (0, отрицательный, NaN) даёт 0 — вызывающий код
 * показывает пустое поле, а не «Infinity» и не «NaN».
 */
export function counterAmount(value: number, rate: number, currencyFrom: string): number {
  if (!Number.isFinite(value) || !Number.isFinite(rate) || rate <= 0) return 0;
  return isKztGive(currencyFrom) ? value / rate : value * rate;
}
